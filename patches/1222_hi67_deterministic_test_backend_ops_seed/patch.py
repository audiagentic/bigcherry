_HELPERS = '''
// bigcherry (HI67 slice 2a): deterministic tensor init for CPU-reference
// correctness evidence. See patches/1222_hi67_deterministic_test_backend_ops_seed/patch.py
// for the full rationale. Opt-in via BIGCHERRY_TEST_DETERMINISTIC_SEED -- unset
// (the default) leaves every existing caller byte-for-byte unchanged.
static uint64_t bigcherry_deterministic_seed() {
    static const uint64_t seed = [] () -> uint64_t {
        const char * env = getenv("BIGCHERRY_TEST_DETERMINISTIC_SEED");
        return env ? strtoull(env, nullptr, 10) : 0;
    }();
    return seed;
}

static bool bigcherry_deterministic_mode() {
    return bigcherry_deterministic_seed() != 0;
}

// Monotonic per-process call index. Two independent processes running the
// identical test case in the identical operand order reach identical
// indices, which is what makes a forced-native and a forced-candidate
// invocation's tensors reproducible from the same base seed.
static uint64_t bigcherry_next_call_index() {
    static std::atomic<uint64_t> counter{0};
    return counter.fetch_add(1, std::memory_order_relaxed);
}

// FNV-1a. Not cryptographic -- only used to let two independent processes
// prove they generated byte-identical tensor data for the same call index.
static uint64_t bigcherry_fnv1a(const void * data, size_t nbytes) {
    uint64_t h = 14695981039346656037ull;
    const uint8_t * p = (const uint8_t *) data;
    for (size_t i = 0; i < nbytes; i++) {
        h ^= p[i];
        h *= 1099511628211ull;
    }
    return h;
}

'''

_BRANCH = '''    size_t nels = ggml_nelements(tensor);
    std::vector<float> data(nels);
    if (bigcherry_deterministic_mode()) {
        // bigcherry (HI67 slice 2a): single-threaded, seeded generator --
        // reproducible across independent processes given the same base
        // seed and call order. See patches/1222_hi67_deterministic_test_backend_ops_seed/patch.py.
        const uint64_t call_index = bigcherry_next_call_index();
        const uint64_t call_seed = bigcherry_deterministic_seed()
            ^ (call_index * 0x9E3779B97F4A7C15ull);
        std::default_random_engine gen(static_cast<unsigned>(call_seed));
        std::uniform_real_distribution<float> distribution(min, max);
        for (size_t i = 0; i < nels; i++) {
            data[i] = distribution(gen);
        }
        const uint64_t digest = bigcherry_fnv1a(data.data(), data.size() * sizeof(float));
        fprintf(stderr, "BIGCHERRY_REF_DIGEST name=%s call_index=%llu digest=%016llx nels=%zu\\n",
                ggml_get_name(tensor), (unsigned long long) call_index,
                (unsigned long long) digest, nels);
    } else {
        // parallel initialization
        static const size_t n_threads = N_THREADS;

        auto init_thread = [&](size_t start, size_t end) {
            thread_local std::default_random_engine gen(std::random_device{}());
            std::uniform_real_distribution<float> distribution(min, max);
            for (size_t i = start; i < end; i++) {
                data[i] = distribution(gen);
            }
        };

        if (n_threads == 1) {
            init_thread(0, nels);
        } else {
            std::vector<std::future<void>> tasks;
            tasks.reserve(n_threads);
            for (size_t i = 0; i < n_threads; i++) {
                size_t start =     i*nels/n_threads;
                size_t end   = (i+1)*nels/n_threads;
                tasks.push_back(std::async(std::launch::async, init_thread, start, end));
            }
            for (auto & t : tasks) {
                t.get();
            }
        }
    }'''

