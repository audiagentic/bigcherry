"""HI67 slice 2a: deterministic tensor init for CPU-reference correctness evidence.

The HI67 correctness contract (RV49, adjudicated by GPT again in RV77 for the
slice 2/3 implementation) compares a candidate's GPU output C against a
CPU-reference result R, and native's own GPU output N against that SAME R:

    E_N = NMSE(R, N)
    E_C = NMSE(R, C)
    E_C <= E_N + correctness_headroom_fraction * (T - E_N)

R comes from test-backend-ops' own CPU-vs-backend comparison. Producing N and
C requires two SEPARATE process invocations (GGML_HIP_FORCE_CANDIDATE=native,
then GGML_HIP_FORCE_CANDIDATE=<candidate>) -- the comparison is only valid if
both processes generated the exact same input tensors, so both are actually
being compared against the same R.

Confirmed via source read (2026-08-20) that this does not hold today:
init_tensor_uniform() seeds a `std::default_random_engine` from
`std::random_device{}()` -- genuinely different per process -- and splits the
work across N_THREADS parallel tasks with no per-thread-substream determinism
either. Two invocations of the same test case get different random tensors.

This patch adds an opt-in deterministic mode, gated by an env var so every
existing caller (upstream's own test suite, BigCherry's other tune-mode
corpus runs) is byte-for-byte unchanged when it is unset:

- BIGCHERRY_TEST_DETERMINISTIC_SEED=<nonzero uint64>: init_tensor_uniform()
  switches to a single-threaded, seeded std::default_random_engine. A
  monotonic call counter (reset per process, incremented once per
  init_tensor_uniform call) is folded into the per-call seed, so repeated
  calls within one process (one per tensor operand in a test case) get
  distinct but still fully reproducible sequences -- two independent
  processes running the identical test case in the identical operand order
  reach identical call indices and therefore identical tensors.
- The generated float buffer's FNV-1a digest is printed on stderr as a
  machine-parseable `BIGCHERRY_REF_DIGEST` line, so a Python driver can
  assert two invocations (forced-native, forced-candidate) actually compared
  against the same input without needing to capture and diff the full tensor.

Scope: only init_tensor_uniform(), the initializer test_mul_mat (the op
family HI67's correctness contract is about) actually uses. init_tensor_
kq_mask()/init_tensor_tril() (attention/triangular-matrix tests, unrelated to
MUL_MAT candidate dispatch) have the same std::random_device non-determinism
but are out of scope for this patch -- tracked as follow-up if a future HI67
slice needs CPU-reference evidence for a non-MUL_MAT op family.
"""

