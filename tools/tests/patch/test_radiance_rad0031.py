def git_blob(content: bytes) -> str:
    return hashlib.sha1(f"blob {len(content)}".encode() + bytes([0]) + content).hexdigest()


def patches():
    spec = importlib.util.spec_from_file_location("rad0031", PACKAGE / "patch.py")
    mod = importlib.util.module_from_spec(spec)
    assert spec.loader
    spec.loader.exec_module(mod)
    return list(mod.PATCHES)


def _fixture(dst: Path) -> None:
    for rel, digest in BLOBS.items():
        source = PIN / rel
        assert git_blob(source.read_bytes()) == digest, rel
        target = dst / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)


def _read(root: Path, rel: str) -> str:
    return (root / rel).read_text(encoding="utf-8")


def test_current_pin_apply_idempotence_and_original_credit_statements():
    with tempfile.TemporaryDirectory(dir=REPO) as temp:
        root = Path(temp)
        _fixture(root)
        ps = patches()
        assert {p.path for p in ps} == set(BLOBS) | OWNED
        first = apply_all(ps, root)
        assert all(p.ok for p in first), first
        assert all(e.status == "applied" for p in first for e in p.results), first
        source = _read(root, "core/runtime/ctx.cpp")
        assert "const bool again = s.step[bank] == step;" in source
        assert "            s.step[bank] = step;\n            heat_note_issue(s, bank, again, n);" in source
        assert ("    route_[(size_t)layer].credited[bank] = true;\n"
                "    heat_credit(layer, bank);") in source
        assert "if (!ok) continue;" in source
        assert "bc_moe_remote_evidence_credit(" in source
        assert "route_.assign((size_t)n_layer, RouteSlot{});" in source
        engine = _read(root, "core/engine.cpp")
        for original in (
            "r.heat.observe(hr.layer, hr.h, n_ex, reps > 1 ? (float)reps : 1.0f);",
            "if (xs) xstats_credit(xs, r.ctx, hr.layer, hr.bank, hr.h);",
            "r.ctx.mark_credited(hr.layer, hr.bank);",
            "++r.heat_credited;",
        ):
            assert original in engine
        heat_block = engine[engine.index("r.heat.observe(hr.layer"):]
        assert heat_block.index("r.heat.observe(hr.layer") < heat_block.index(
            "if (xs) xstats_credit(xs, r.ctx") < heat_block.index(
            "r.ctx.mark_credited(hr.layer")
        assert engine.index("bc_moe_heat_static_drain(") < engine.index(
            "bc_moe_remote_evidence_static_drain(")
        assert engine.count("r.ctx.mark_credited(hr.layer, hr.bank);") == 2
        assert "if (!r.heat.enabled()) {" in engine

        # Upstream edits are one-line/short calls/declarations only, no
        # deleted or re-ordered original statements.
        for rel in BLOBS:
            before = (PIN / rel).read_text().splitlines()
            after = _read(root, rel).splitlines()
            removed = [line for line in difflib.unified_diff(before, after, n=0)
                       if line.startswith("-") and not line.startswith("---")]
            assert not removed, (rel, removed[:10])

        snapshot = {p.path: _read(root, p.path) for p in ps}
        second = apply_all(ps, root)
        assert all(p.ok for p in second), second
        assert all(e.status == "already-applied" for p in second for e in p.results)
        assert {p.path: _read(root, p.path) for p in ps} == snapshot


def test_anchor_drift_fails_closed_and_does_not_edit_original_fixture():
    ps = patches()
    for rel, original, replacement in MUTANTS:
        with tempfile.TemporaryDirectory(dir=REPO) as temp:
            root = Path(temp)
            _fixture(root)
            source = _read(root, rel)
            assert source.count(original) == 1, (rel, original)
            (root / rel).write_text(source.replace(original, replacement))
            result = apply_all(ps, root)
            assert any(not p.ok for p in result), (rel, result)
            assert _read(root, rel).count(replacement) == 1
    for rel, digest in BLOBS.items():
        assert git_blob((PIN / rel).read_bytes()) == digest


def test_create_files_fails_closed_on_conflicting_upstream_file():
    with tempfile.TemporaryDirectory(dir=REPO) as temp:
        root = Path(temp)
        _fixture(root)
        (root / "abi").mkdir()
        (root / "abi/rad_moe_heat.h").write_text("foreign ABI\n")
        result = apply_all(patches(), root)
        assert not all(p.ok for p in result)
        assert (root / "abi/rad_moe_heat.h").read_text() == "foreign ABI\n"


def test_registry_and_fake_ctx_card_free_compiled_oracle():
    # Same package-owned C++ source that the moe-remote CTest target compiles.
    if not shutil.which("g++"):
        raise AssertionError("g++ required for the CPU-only ABI oracle")
    with tempfile.TemporaryDirectory(dir=REPO) as temp:
        exe = Path(temp) / "r3_heat_observer_abi_test"
        cmd = [
            "g++", "-std=c++17", "-O0", "-pthread", "-Wall", "-Wextra", "-Werror",
            "-I", str(PACKAGE),
            str(REPO / "engines/radiance/components/moe-remote/heat_observer_abi_test.cpp"),
            str(PACKAGE / "bc_moe_heat_registry.cpp"),
            "-o", str(exe),
        ]
        subprocess.run(cmd, check=True, capture_output=True, text=True)
        subprocess.run([str(exe)], check=True, capture_output=True, text=True)
