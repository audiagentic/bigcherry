"""VTP14: original-BF16-conv Qwen GDN mathematical GPU oracle, opt-in.

Reuses VTP04/VTP13's source-digested multi-arch HIP build, exclusive
agent-lease preflight, empty KFD requirement, and immutable hardware
receipts. Input QKV/a/b/z are synthetic preprojected BF16 values. The
real original checkpoint conv1d, A_log, dt_bias and norm are consumed;
the independent CPU output files are generated by xtx27_vtp14_gdn_exact.
This does NOT establish full-model execution, native plugin performance,
or speculative/prefill GDN correctness.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import subprocess
import sys
from pathlib import Path

import xtx27_vtp_micro as micro

ROOT = micro.ROOT
SOURCE = Path(__file__).with_name("xtx27_vtp14_gdn_exact.hip")
SOURCES = {"gdn_exact": SOURCE}
SCRATCH = Path(os.environ.get("BC_WORK_ROOT", ROOT.parent)) / "xtx27-prefill" / "vtp14-gdn-gpu"
LEASE_PURPOSE = "VTP14: partial-real-BF16 Qwen GDN exact-math three-GPU oracle"
RECEIPT_TYPE = "VTP14_THREE_GPU_QWEN_GDN_REAL_CONV_LEARNED_DECAY_ORACLE"
ROLES = ("xtx0", "xtx1", "r9700")


def sha(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as stream:
        for part in iter(lambda: stream.read(1024 * 1024), b""):
            h.update(part)
    return h.hexdigest()


def validate_reference(ref: Path, pack_path: Path) -> tuple[dict, dict, dict]:
    receipt = json.loads(ref.read_text())
    pack = json.loads(pack_path.read_text())
    if receipt.get("source_sha256") != sha(Path(__file__).with_name("xtx27_vtp14_gdn_exact.py")):
        raise ValueError("CPU reference writer changed since oracle generation")
    if (receipt.get("schema") != "vtp14-gdn-partial-real-bf16-math-v1"
            or receipt.get("status") != "CARD_FREE_QWEN_GDN_MATH_AND_SHARD_CONTINUITY_PASS_NOT_GPU"):
        raise ValueError("reference is not a completed VTP14 independent CPU oracle")
    if (pack.get("status") != "EXACT_ORIGINAL_BF16_GDN_QKV_CONV_PACK_PASS_NOT_RUNTIME"
            or pack.get("layer") != 0 or receipt.get("layer") != 0):
        raise ValueError("pack and oracle must be original layer 0 BF16")
    rows = receipt.get("rows")
    if type(rows) is not int or not 1 <= rows <= 8:
        raise ValueError("GPU rows must be bounded to 1..8")
    if receipt.get("checkpoint_source_sha256") != pack["outputs"]["conv1d"]["source_payload_sha256"]:
        raise ValueError("reference source and original convolution weight hash disagree")
    args = ["--rows", str(rows)]
    coeff = receipt.get("reference_coefficients")
    if not isinstance(coeff, dict):
        raise TypeError("reference must export original learned coefficient packet")
    coeff_path = Path(coeff["file"])
    if sha(coeff_path) != coeff["sha256"] or coeff_path.stat().st_size != 224 * 4:
        raise ValueError("learned parameter packet changed")
    args.extend(["--coefficients", str(coeff_path)])
    for role, nheads, nkeys in zip(ROLES, (12, 12, 24), (4, 4, 8), strict=True):
        expected = receipt["rank_results"][role]
        if expected["heads"] != nheads or expected["state_elements"] != nheads * 128 * 128:
            raise ValueError(f"changed {role} head geometry")
        oracle = Path(expected["oracle_file"])
        if sha(oracle) != expected["output_sha256"]:
            raise ValueError(f"{role} independent output bytes changed")
        if oracle.stat().st_size != rows * nheads * 128 * 4:
            raise ValueError(f"{role} original oracle output shape changed")
        packed = pack["outputs"]["conv1d"]["ranks"][role]
        conv = Path(packed["path"])
        if sha(conv) != packed["sha256"] or packed["bytes"] != (2 * nkeys + nheads) * 128 * 4 * 2:
            raise ValueError(f"{role} original BF16 convolution weights changed")
        args.extend([f"--conv-{role}", str(conv), f"--oracle-{role}", str(oracle)])
    return receipt, pack, {
        "args": args, "rows": rows,
        "reference_sha256": sha(ref), "pack_sha256": sha(pack_path),
        "reference_file": str(ref), "pack_file": str(pack_path),
    }


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--phase", choices=("plan", "compile", "gpu"), default="plan")
    p.add_argument("--run", action="store_true")
    p.add_argument("--_under-lease", action="store_true", help=argparse.SUPPRESS)
    p.add_argument("--reference", type=Path,
                   help="completed independent CPU oracle receipt (required for GPU)")
    p.add_argument("--pack-receipt", type=Path,
                   help="completed exact original BF16 rank-packing receipt")
    p.add_argument("--iterations", type=int, default=5)
    p.add_argument("--scratch", type=Path, default=SCRATCH)
    p.add_argument("--hipcc")
    a = p.parse_args(argv)
    if a.phase != "plan" and not a.run:
        p.error("compile or GPU requires explicit --run")
    if a._under_lease and os.environ.get("VTP04_LEASED") != "1":
        p.error("internal GPU subprocess requires exclusive agent-lease wrapper")
    if not 1 <= a.iterations <= 30:
        p.error("iterations must be 1..30")
    try:
        _ref, _pack, case = (validate_reference(a.reference, a.pack_receipt)
                           if a.reference and a.pack_receipt else (None, None, None))
    except (KeyError, TypeError, FileNotFoundError, ValueError, OSError, json.JSONDecodeError) as e:
        p.error(str(e))
    if a.phase == "gpu" and case is None:
        p.error("GPU phase requires --reference and --pack-receipt")
    digest = micro.source_digest(SOURCES)
    hashes = {
        "driver_sha256": sha(Path(__file__)),
        "source_sha256": sha(SOURCE),
        "shared_driver_sha256": sha(Path(micro.__file__)),
    }
    if a.phase == "plan":
        print(json.dumps({
            "schema": "vtp14-real-conv-gdn-GPU-oracle-v1",
            "phase": "card_free",
            "source_digest": digest, "code_hashes": hashes,
            "independent_reference": case,
            "gpu_required_to_complete": True,
            "not_full_qwen_gdn": True, "not_model_benchmark": True,
        }, indent=2))
        return 0
    hipcc = micro.compiler_path(a.hipcc)
    if hipcc is None:
        p.error("missing HIP compiler")
    scratch = a.scratch.resolve()
    if scratch == ROOT or ROOT in scratch.parents:
        p.error("scratch must be outside Git worktree")
    binary = micro.build_binaries(hipcc, scratch, digest, sources=SOURCES)
    if a.phase == "compile":
        print(json.dumps({"status": "multiarch_compiled_without_GPU",
                          "source_digest": digest,
                          "binary": str(binary["gdn_exact"])}, indent=2))
        return 0
    if not a._under_lease:
        command = [
            sys.executable, str(Path(__file__).resolve()), "--phase", "gpu",
            "--run", "--_under-lease",
            "--reference", str(a.reference),
            "--pack-receipt", str(a.pack_receipt),
            "--iterations", str(a.iterations), "--scratch", str(scratch),
            "--hipcc", str(hipcc),
        ]
        return subprocess.run([
            "agent-lease", "acquire", "gpu", "--ttl", "30m",
            "--purpose", LEASE_PURPOSE, "--", "env", "VTP04_LEASED=1", *command,
        ], check=False).returncode
    # The reused runner refuses an inherited device mask, wrong lease
    # purpose or any pre-existing KFD process before HIP starts.
    cases = [{
        "kind": "gdn_exact",
        "label": f"qwen-gdn-original-bf16-conv-m{case['rows']}",
        "args": [*case["args"], "--iterations", str(a.iterations)],
        "data_definition": "genuine 3-physical-GPU 4/4/8 key 12/12/24 value"
                           " original-BF16 conv and learned decay/normalization;"
                           " independent per-rank Python Qwen recurrence output oracle;"
                           " preprojected synthetic BF16 ingress, no engine model serving",
    }]
    output = micro.run_leased(
        scratch=scratch, binaries=binary, cases=cases, digest=digest,
        purpose=LEASE_PURPOSE, receipt_type=RECEIPT_TYPE,
    )
    receipt_path = output / "summary.json"
    record = json.loads(receipt_path.read_text())
    record.update({
        "schema": "vtp14-real-conv-gdn-GPU-oracle-v1",
        "source_receipts": case, "code_hashes": hashes,
        "not_full_qwen_gdn": True, "not_model_benchmark": True,
        "original_checkpoint_qkv_projection": False,
    })
    receipt_path.write_text(json.dumps(record, indent=2) + "\n")
    print(json.dumps({"status": "completed_partial_real_GDN_GPU_oracle_not_full_model",
                      "receipt": str(receipt_path)}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
