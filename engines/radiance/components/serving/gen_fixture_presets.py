#!/usr/bin/env python3
"""Generate test_config_presets.inc: the engine-free resolver tests' presets, one per shipped config YAML.

Each preset is named after its engines/radiance/configs/NAME.yaml and carries exactly what that file states, in the shape the
resolver takes (ranks, helpers, tables, the tp wire, the model, and the model options as resolver settings). A test
(tools/tests/release/test_native_profiles.py) regenerates the file and fails when it differs, so a preset cannot drift from its
YAML. Usage: gen_fixture_presets.py [--write]
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
CONFIGS = HERE.parent.parent / "configs"
OUT = HERE / "test_config_presets.inc"
# native model option -> resolver key (the options bc-serve's resolver reads from the YAML's native half)
NATIVE = {
    "max-model-len": "service.max_context", "max-num-seqs": "service.max_sessions",
    "max-num-batched-tokens": "engine.max_num_batched_tokens", "checkpoint-interval": "engine.checkpoint_interval",
    "placement": "engine.placement", "kv-cache-dtype": "engine.kv_cache_dtype",
    "ngram-placement": "engine.ngram_placement", "num-speculative-tokens": "engine.num_speculative_tokens",
    "prefix-resume": "engine.prefix_resume", "rope-scaling": "engine.rope_scaling",
    "p2p": "tuning.p2p", "pipelined-prefill": "tuning.pipelined_prefill",
    "pipelined-prefill-min-rows": "tuning.pipelined_prefill_min_rows", "prefill-governor": "tuning.prefill_governor",
    "prefill-interleave": "tuning.prefill_interleave", "tp-ownership": "tuning.tp_ownership", "tune-pin": "tuning.tune_pin",
    "attn-prefill-fp8": "tuning.attn_prefill_fp8", "busy-prefill-chunk": "tuning.busy_prefill_chunk",
    "state-cache-dtype": "tuning.state_cache_dtype", "tp-wire-min-kb": "tuning.tp_wire_min_kb",
}


def cpp(value) -> str:
    return json.dumps(value) if not isinstance(value, bool) else ("true" if value else "false")


def preset(path: Path) -> str:
    doc = yaml.safe_load(path.read_text(encoding="utf-8"))
    model = next(iter(doc["models"].values()))
    x = doc["x-bigcherry"]
    lines = [f'    if (name == "{path.stem}") {{', "        Preset p;", f'        p.name = {cpp(path.stem)};',
             f"        p.description = {cpp(x['description'])};", f"        p.model = {cpp(model['model'])};"]
    if "tp-wire" in model:
        lines.append(f"        p.tp_wire = {cpp(model['tp-wire'])};")
    for rank in x["ranks"]:
        lines.append(f'        p.ranks.push_back({{{cpp(rank["arch"])}, {rank["count"]}}});')
    for helper in x.get("helpers", []):
        count = -1 if helper["count"] == "all" else helper["count"]
        lines.append(f'        p.helpers.push_back({{{cpp(helper["arch"])}, {count}, {cpp(helper["placement"])}, '
                     f'{"std::optional<std::int64_t>(%d)" % helper["budget-mib"] if "budget-mib" in helper else "std::nullopt"}, '
                     f'{"std::optional<std::int64_t>(%d)" % helper["share"] if "share" in helper else "std::nullopt"}}});')
    for table in ("service", "memory", "handoff", "helper", "kernels"):
        for key, value in x.get(table, {}).items():
            lines.append(f'        p.{table}["{key}"] = {cpp(value)};')
    for key, value in model.items():
        if key in NATIVE:
            # The manifest's existing busy-chunk field carries native MODE text,
            # even when the YAML authors its positive token limit as an integer.
            if key == "busy-prefill-chunk" and type(value) is int:
                value = str(value)
            lines.append(f'        p.sets.push_back({cpp(NATIVE[key] + "=" + json.dumps(value))});')
    lines += ["        return p;", "    }"]
    return "\n".join(lines)


def render() -> str:
    body = "\n".join(preset(p) for p in sorted(CONFIGS.glob("*.yaml")))
    return ("// Generated by gen_fixture_presets.py from engines/radiance/configs/*.yaml: do not edit.\n" + body + "\n")


if __name__ == "__main__":
    text = render()
    if "--write" in sys.argv:
        OUT.write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)
